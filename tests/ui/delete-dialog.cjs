const {JSDOM}=require('jsdom');
const dom=new JSDOM('<div id="root"></div>',{url:'https://example.test'});
global.window=dom.window;global.document=dom.window.document;global.HTMLElement=dom.window.HTMLElement;global.IS_REACT_ACT_ENVIRONMENT=true;
const React=require('react'),{act}=React,{createRoot}=require('react-dom/client');
const {ConfirmDelete}=require(process.env.CHAT_LIST_BUNDLE);
const assert=require('node:assert/strict');
(async()=>{
 let cancel=0,reject,calls=0;
 const trigger=document.createElement('button');trigger.textContent='Зовнішня кнопка';document.body.prepend(trigger);trigger.focus();
 const root=createRoot(document.getElementById('root'));
 await act(async()=>root.render(React.createElement(ConfirmDelete,{d:{id:'test',title:'Тест'},onCancel:()=>cancel++,onConfirm:()=>{calls++;return new Promise((_,r)=>reject=r)}})));
 assert.equal(document.activeElement.textContent,'Скасувати');
 const tab=async(shift=false)=>{const e=new window.KeyboardEvent('keydown',{key:'Tab',shiftKey:shift,cancelable:true});await act(async()=>window.dispatchEvent(e));assert.equal(e.defaultPrevented,true);};
 await tab(true);assert.equal(document.activeElement.textContent,'Видалити');
 await tab();assert.equal(document.activeElement.textContent,'Скасувати');
 trigger.focus();await tab();assert.equal(document.activeElement.textContent,'Скасувати');
 await act(async()=>document.querySelector('.danger').click());
 assert.equal(calls,1);assert.equal(document.querySelector('[role=status]').textContent,'Видаляємо чат та його файли. Зачекайте…');
 assert.ok([...document.querySelectorAll('.modal button')].every(b=>b.disabled));
 await act(async()=>{window.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape'}));document.querySelector('.overlay').dispatchEvent(new window.MouseEvent('mousedown',{bubbles:true}));});
 assert.equal(cancel,0);
 await tab();assert.equal(document.activeElement,document.querySelector('.modal'));
 await act(async()=>reject(new Error('Тестова помилка')));
 assert.equal(document.querySelector('[role=alert]').textContent,'Тестова помилка');
 assert.ok([...document.querySelectorAll('.modal button')].every(b=>!b.disabled));
 await act(async()=>window.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape'})));
 assert.equal(cancel,1);
 await act(async()=>root.unmount());
 assert.equal(document.activeElement,trigger);
 console.log('PASS: Tab/Shift+Tab wrapping, focus containment while busy, focus restoration, deletion feedback and error recovery');
})().catch(e=>{console.error(e);process.exitCode=1});
